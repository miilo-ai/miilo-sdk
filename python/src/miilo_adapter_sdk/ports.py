from __future__ import annotations
from collections.abc import AsyncIterator
from typing import Protocol
from .models import ActionInvocation, ActionResult, ObservatoryEvent, ObservatorySnapshot, ProviderDescriptor, VoiceStreamEvent, VoiceTextTurnRequest, VoiceTurnResult

class MiiloAdapter(Protocol):
    async def describe_provider(self) -> ProviderDescriptor: ...
    async def get_snapshot(self, cursor: str | None = None) -> ObservatorySnapshot: ...
    def subscribe(self, cursor: str | None = None) -> AsyncIterator[ObservatoryEvent]: ...
    async def invoke(self, action: ActionInvocation) -> ActionResult: ...

class SpeechMiiloAdapter(MiiloAdapter, Protocol):
    async def voice_turn(self, audio: bytes, filename: str, content_type: str) -> VoiceTurnResult: ...
    def voice_turn_stream(self, audio: bytes, filename: str, content_type: str) -> AsyncIterator[VoiceStreamEvent]: ...
    def voice_text_turn_stream(self, request: VoiceTextTurnRequest) -> AsyncIterator[VoiceStreamEvent]: ...
